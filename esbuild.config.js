import esbuild from "esbuild";
import { builtinModules } from "node:module";
import { sassPlugin } from "esbuild-sass-plugin";
import fs from "fs";

const banner = `/* THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv.includes("production");
const watch = process.argv.includes("--watch");

const outdir = "dist";

// Obsidian loads plugins via manifest.json next to main.js, so copy the
// source manifest into the output dir after every (re)build, including watch.
const copyManifestPlugin = {
  name: "copy-manifest",
  setup(build) {
    build.onEnd(() => {
      fs.mkdirSync(outdir, { recursive: true });
      fs.copyFileSync("manifest.json", `${outdir}/manifest.json`);
    });
  },
};

const context = await esbuild.context({
  bundle: true,
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts", "src/ui/styles/styles.scss"],
  entryNames: "[name]",
  outdir,
  external: [
    "obsidian",
    "electron",
    // Obsidian provides CodeMirror 6 and Lezer at runtime. Bundling our own
    // copies would duplicate their singletons and break instanceof checks.
    "@codemirror/*",
    "@lezer/*",
    ...builtinModules,
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  define: {
    "process.env.NODE_ENV": prod ? '"production"' : '"development"',
  },

  minify: prod,
  minifyWhitespace: prod,
  minifyIdentifiers: prod,
  minifySyntax: prod,
  plugins: [
    sassPlugin({
      type: "css",
      style: "compressed",
    }),
    copyManifestPlugin,
  ],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else if (watch) {
  await context.watch(); // Watch for file changes in dev mode (npm run dev)
} else {
  await context.rebuild(); // One-shot dev build (reload.sh)
  process.exit(0);
}